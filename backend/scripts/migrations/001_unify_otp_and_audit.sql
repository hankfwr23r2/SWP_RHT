-- Upgrade an existing PostgreSQL schema. Stop ALL old backend instances first.
-- Run using psql -v ON_ERROR_STOP=1. This script is transactional and rerunnable
-- before 002; it preserves source tables until reconciliation has succeeded.
BEGIN;
LOCK TABLE email_verification_otps, password_reset_otps, location_change_log,
    document_requirement_change_log, system_log, log IN ACCESS EXCLUSIVE MODE;

CREATE TABLE IF NOT EXISTS email_otp (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL,
    purpose varchar(30) NOT NULL,
    otp_hash varchar(100) NOT NULL,
    expires_at timestamptz NOT NULL,
    last_sent_at timestamptz NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    CONSTRAINT uk_email_otp_email_purpose UNIQUE(email, purpose),
    CONSTRAINT ck_email_otp_values CHECK (attempts >= 0 AND purpose IN ('VERIFY_EMAIL','RESET_PASSWORD'))
);
CREATE INDEX IF NOT EXISTS idx_email_otp_expiry ON email_otp(expires_at);

-- Do not silently choose a winner if old case-insensitive emails collide.
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM email_verification_otps GROUP BY lower(btrim(email)) HAVING count(*) > 1)
       OR EXISTS (SELECT 1 FROM password_reset_otps GROUP BY lower(btrim(email)) HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Duplicate normalized OTP email; reconcile sources before migrating';
    END IF;
END $$;
INSERT INTO email_otp(email,purpose,otp_hash,expires_at,last_sent_at,attempts)
SELECT lower(btrim(email)), 'VERIFY_EMAIL', otp_hash, expires_at, last_sent_at, attempts FROM email_verification_otps
UNION ALL
SELECT lower(btrim(email)), 'RESET_PASSWORD', otp_hash, expires_at, last_sent_at, attempts FROM password_reset_otps
ON CONFLICT(email,purpose) DO NOTHING;

-- Both tables must agree on retries; never overwrite tokens received after cutover.
DO $$ BEGIN
    IF EXISTS (
        SELECT 1 FROM (
            SELECT lower(btrim(email)) email, 'VERIFY_EMAIL' purpose, otp_hash, expires_at, last_sent_at, attempts FROM email_verification_otps
            UNION ALL
            SELECT lower(btrim(email)), 'RESET_PASSWORD', otp_hash, expires_at, last_sent_at, attempts FROM password_reset_otps
        ) old LEFT JOIN email_otp n USING(email,purpose)
        WHERE n.id IS NULL OR (n.otp_hash,n.expires_at,n.last_sent_at,n.attempts)
            IS DISTINCT FROM (old.otp_hash,old.expires_at,old.last_sent_at,old.attempts)
    ) THEN RAISE EXCEPTION 'OTP destination differs; do not rerun upgrade after accepting new writes'; END IF;
END $$;

ALTER TABLE system_log ADD COLUMN IF NOT EXISTS source_table varchar(100);
ALTER TABLE system_log ADD COLUMN IF NOT EXISTS source_id bigint;
CREATE UNIQUE INDEX IF NOT EXISTS uk_system_log_source ON system_log(source_table,source_id);

-- Keep one imported audit per source field; retain source identity rather than
-- guessing that a nearby full snapshot represents the same historical event.
INSERT INTO system_log(action_type,target_table,target_recordid,target_key,actor_name,
    created_at,old_data,new_data,data_version,description,source_table,source_id)
SELECT 'UPDATE_LOCATION','LOCATION',locationid,locationid::text,changed_by,
    changed_at,jsonb_build_object(field_name,old_value)::text,jsonb_build_object(field_name,new_value)::text,
    1,'Imported legacy field history (may overlap existing action audit)','location_change_log',id
FROM location_change_log ON CONFLICT(source_table,source_id) DO NOTHING;
INSERT INTO system_log(action_type,target_table,target_recordid,target_key,actor_name,
    created_at,old_data,new_data,data_version,description,source_table,source_id)
SELECT 'UPDATE_DOCUMENT_REQUIREMENT','DOCUMENT_REQUIREMENT',requirement_id,requirement_id::text,changed_by,
    changed_at,jsonb_build_object(field_name,old_value)::text,jsonb_build_object(field_name,new_value)::text,
    1,'Imported legacy field history (may overlap existing action audit)','document_requirement_change_log',id
FROM document_requirement_change_log ON CONFLICT(source_table,source_id) DO NOTHING;

ALTER TABLE log ADD COLUMN IF NOT EXISTS actor_username varchar(255);
ALTER TABLE log ADD COLUMN IF NOT EXISTS target_table varchar(100);
ALTER TABLE log ADD COLUMN IF NOT EXISTS target_record_id integer;
ALTER TABLE log ADD COLUMN IF NOT EXISTS source_system_log_id integer;
ALTER TABLE log ADD COLUMN IF NOT EXISTS metadata_json text;
CREATE UNIQUE INDEX IF NOT EXISTS uk_log_source_system_log ON log(source_system_log_id);
-- Upgrade the existing key without changing IDs referenced by incident.logid.
DO $$ BEGIN
    IF (SELECT is_identity FROM information_schema.columns WHERE table_schema=current_schema()
            AND table_name='log' AND column_name='logid') = 'NO' THEN
        ALTER TABLE log ALTER COLUMN logid DROP DEFAULT;
        ALTER TABLE log ALTER COLUMN logid ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;
SELECT setval(pg_get_serial_sequence('log','logid'), coalesce((SELECT max(logid) FROM log),0)+1, false);

-- Unknown targets stop the migration rather than silently losing historical data.
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM system_log WHERE target_table IS NULL OR target_table NOT IN
        ('USER','SYSTEM_CONFIG','SERVICE','ROUTE','LOCATION','DOCUMENT_REQUIREMENT','HORSE_TYPE','BOOKING','INCIDENT')) THEN
        RAISE EXCEPTION 'Unclassified system_log target; review before migration';
    END IF;
END $$;
INSERT INTO log(log_type,bookingid,actor_username,target_table,target_record_id,note,created_at,metadata_json,source_system_log_id)
SELECT s.action_type,
    CASE WHEN s.action_type='VEHICLE_RETURNED_HQ' THEN NULL
         WHEN EXISTS(SELECT 1 FROM booking b WHERE b.bookingid=s.target_recordid) THEN s.target_recordid ELSE NULL END,
    coalesce(s.actor_name,u.username),
    CASE WHEN s.action_type='VEHICLE_RETURNED_HQ' THEN 'VEHICLE' ELSE 'BOOKING' END,
    s.target_recordid, s.new_data, s.created_at, to_jsonb(s)::text, s.system_logid
FROM system_log s LEFT JOIN users u ON u.userid=s.action_by_userid
WHERE s.target_table IN ('BOOKING','INCIDENT')
ON CONFLICT(source_system_log_id) DO NOTHING;

DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM system_log s WHERE s.target_table IN ('BOOKING','INCIDENT') AND NOT EXISTS
        (SELECT 1 FROM log l WHERE l.source_system_log_id=s.system_logid AND l.metadata_json::jsonb=to_jsonb(s))) THEN
        RAISE EXCEPTION 'Operational audit reconciliation failed';
    END IF;
END $$;
DELETE FROM system_log WHERE target_table IN ('BOOKING','INCIDENT');
COMMIT;
