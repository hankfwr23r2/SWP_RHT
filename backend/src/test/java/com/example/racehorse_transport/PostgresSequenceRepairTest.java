package com.example.racehorse_transport;

import org.junit.jupiter.api.Test;
import org.testcontainers.postgresql.PostgreSQLContainer;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class PostgresSequenceRepairTest {
    @Test
    void repairsImportedIdsWithoutRewindingAheadOrEmptySequencesAndCanReplay() throws Exception {
        try (var postgres = new PostgreSQLContainer("postgres:16-alpine")) {
            postgres.start();
            try (var connection = connect(postgres)) {
                execute(connection, """
                        CREATE TABLE horse_document(documentid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, file_url text);
                        INSERT INTO horse_document VALUES (27, 'passport.png'), (98, 'vaccine.png');
                        SELECT setval(pg_get_serial_sequence('horse_document', 'documentid'), 26, true);
                        CREATE TABLE booking(bookingid bigserial PRIMARY KEY);
                        INSERT INTO booking VALUES (59);
                        CREATE TABLE ahead(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
                        INSERT INTO ahead VALUES (50);
                        SELECT setval(pg_get_serial_sequence('ahead', 'id'), 200, true);
                        CREATE TABLE reserved(id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 500) PRIMARY KEY);
                        INSERT INTO reserved VALUES (98);
                        CREATE TABLE empty(id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY);
                        CREATE TABLE empty_used(id serial PRIMARY KEY);
                        INSERT INTO empty_used DEFAULT VALUES;
                        DELETE FROM empty_used;
                        CREATE TABLE "Horse Docs"("Document ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
                        INSERT INTO "Horse Docs" VALUES (123);
                        CREATE TABLE stepped(id integer GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 5) PRIMARY KEY);
                        INSERT INTO stepped VALUES (13);
                        """);

                assertThatThrownBy(() -> execute(connection, "INSERT INTO horse_document(file_url) VALUES ('new.png')"))
                        .isInstanceOf(SQLException.class).hasMessageContaining("horse_document_pkey");

                repair(connection);
                repair(connection);

                assertThat(number(connection, "INSERT INTO horse_document(file_url) VALUES ('new.png') RETURNING documentid")).isEqualTo(99);
                assertThat(number(connection, "SELECT count(*) FROM horse_document WHERE documentid IN (27,98) AND file_url IN ('passport.png','vaccine.png')")).isEqualTo(2);
                assertThat(number(connection, "INSERT INTO booking DEFAULT VALUES RETURNING bookingid")).isEqualTo(60);
                assertThat(number(connection, "INSERT INTO ahead DEFAULT VALUES RETURNING id")).isEqualTo(201);
                assertThat(number(connection, "INSERT INTO reserved DEFAULT VALUES RETURNING id")).isEqualTo(500);
                assertThat(number(connection, "INSERT INTO empty DEFAULT VALUES RETURNING id")).isEqualTo(10);
                assertThat(number(connection, "INSERT INTO empty_used DEFAULT VALUES RETURNING id")).isEqualTo(2);
                assertThat(number(connection, "INSERT INTO \"Horse Docs\" DEFAULT VALUES RETURNING \"Document ID\"")).isEqualTo(124);
                assertThat(number(connection, "INSERT INTO stepped DEFAULT VALUES RETURNING id")).isEqualTo(16);

                repair(connection);
                assertThat(number(connection, "INSERT INTO horse_document(file_url) VALUES ('lab.png') RETURNING documentid")).isEqualTo(100);
            }
        }
    }

    @Test
    void discardsCachedIdsWhenRestartingASequence() throws Exception {
        try (var postgres = new PostgreSQLContainer("postgres:16-alpine")) {
            postgres.start();
            try (var repairConnection = connect(postgres); var writer = connect(postgres)) {
                execute(repairConnection, "CREATE TABLE horse_document(documentid integer GENERATED BY DEFAULT AS IDENTITY (CACHE 5) PRIMARY KEY)");
                assertThat(number(writer, "INSERT INTO horse_document DEFAULT VALUES RETURNING documentid")).isEqualTo(1);
                execute(repairConnection, "INSERT INTO horse_document VALUES (98)");

                repair(repairConnection);

                assertThat(number(writer, "INSERT INTO horse_document DEFAULT VALUES RETURNING documentid")).isEqualTo(99);
            }
        }
    }

    @Test
    void rollsBackEarlierRepairsIfAnotherSequenceCannotAdvance() throws Exception {
        try (var postgres = new PostgreSQLContainer("postgres:16-alpine")) {
            postgres.start();
            try (var connection = connect(postgres)) {
                execute(connection, """
                        CREATE TABLE a_repairable(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
                        INSERT INTO a_repairable VALUES (98);
                        CREATE TABLE z_exhausted(id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
                        INSERT INTO z_exhausted VALUES (32767);
                        """);

                assertThatThrownBy(() -> repair(connection)).isInstanceOf(SQLException.class);

                assertThat(number(connection, "INSERT INTO a_repairable DEFAULT VALUES RETURNING id")).isEqualTo(1);
                assertThat(number(connection, "SELECT count(*) FROM a_repairable WHERE id=98")).isEqualTo(1);
            }
        }
    }

    private Connection connect(PostgreSQLContainer postgres) throws SQLException {
        return DriverManager.getConnection(postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
    }

    private void repair(Connection connection) throws Exception {
        execute(connection, Files.readString(Path.of("../docker/postgres/repair_sequences.sql")));
    }

    private void execute(Connection connection, String sql) throws SQLException {
        try (var statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private long number(Connection connection, String sql) throws SQLException {
        try (var statement = connection.createStatement(); var rows = statement.executeQuery(sql)) {
            rows.next();
            return rows.getLong(1);
        }
    }
}
