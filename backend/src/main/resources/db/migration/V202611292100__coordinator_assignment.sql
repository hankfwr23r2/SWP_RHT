ALTER TABLE departure
    ADD COLUMN coordinator_id bigint REFERENCES staff(user_id),
    ADD COLUMN coordinator_reminded_on date;
ALTER TABLE vehicle_trip ADD COLUMN coordinator_id bigint REFERENCES staff(user_id);

CREATE INDEX ix_departure_coordinator ON departure(coordinator_id);
CREATE INDEX ix_vehicle_trip_coordinator ON vehicle_trip(coordinator_id);

CREATE TABLE coordinator_assignment_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id bigint REFERENCES departure(id),
    vehicle_trip_id bigint REFERENCES vehicle_trip(id),
    from_staff_id bigint REFERENCES staff(user_id),
    to_staff_id bigint NOT NULL REFERENCES staff(user_id),
    changed_by bigint NOT NULL REFERENCES app_user(id),
    reason varchar(500),
    changed_at timestamptz NOT NULL,
    CHECK ((departure_id IS NULL) <> (vehicle_trip_id IS NULL))
);

CREATE INDEX ix_coordinator_history_departure ON coordinator_assignment_history(departure_id);
CREATE INDEX ix_coordinator_history_trip ON coordinator_assignment_history(vehicle_trip_id);

