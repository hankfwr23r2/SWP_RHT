ALTER TABLE booking ADD COLUMN specialist_id bigint REFERENCES staff(user_id);
CREATE INDEX ix_booking_specialist ON booking (specialist_id);

CREATE TABLE booking_specialist_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking(id),
    from_staff_id bigint REFERENCES staff(user_id),
    to_staff_id bigint NOT NULL REFERENCES staff(user_id),
    changed_by bigint NOT NULL REFERENCES app_user(id),
    reason varchar(1000),
    changed_at timestamptz NOT NULL
);
CREATE INDEX ix_booking_specialist_history_booking ON booking_specialist_history (booking_id);
