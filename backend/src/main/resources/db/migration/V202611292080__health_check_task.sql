CREATE TABLE health_check_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_horse_id bigint NOT NULL REFERENCES booking_horse(id),
    vehicle_trip_id bigint REFERENCES vehicle_trip(id),
    horse_stay_id bigint REFERENCES horse_stay(id),
    assigned_to bigint NOT NULL REFERENCES staff(user_id),
    assigned_by bigint NOT NULL REFERENCES staff(user_id),
    assigned_at timestamptz NOT NULL,
    check_type varchar(30) NOT NULL CHECK (check_type IN ('ROUTINE', 'FOLLOW_UP', 'BEFORE_DEPARTURE')),
    due_at timestamptz NOT NULL,
    status varchar(30) NOT NULL CHECK (status IN ('ASSIGNED', 'ACCEPTED', 'DONE', 'CANCELLED')),
    note varchar(500),
    accepted_at timestamptz,
    done_at timestamptz,
    health_log_id bigint REFERENCES horse_health_log(id),
    cancel_reason varchar(500),
    overdue_notified_at timestamptz,
    CHECK (num_nonnulls(vehicle_trip_id, horse_stay_id) = 1),
    CHECK ((status = 'DONE') = (health_log_id IS NOT NULL AND done_at IS NOT NULL)),
    CHECK ((status = 'CANCELLED') = (cancel_reason IS NOT NULL))
);

CREATE INDEX ix_health_check_task_assignee ON health_check_task (assigned_to, status, due_at);
CREATE INDEX ix_health_check_task_horse ON health_check_task (booking_horse_id);
CREATE INDEX ix_health_check_task_due ON health_check_task (due_at)
    WHERE overdue_notified_at IS NULL AND status IN ('ASSIGNED', 'ACCEPTED');
