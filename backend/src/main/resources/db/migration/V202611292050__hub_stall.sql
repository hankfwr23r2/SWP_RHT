CREATE TABLE hub_stall (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id bigint NOT NULL REFERENCES location(id),
    code varchar(40) NOT NULL,
    stall_kind varchar(16) NOT NULL CHECK (stall_kind IN ('STANDARD', 'ISOLATION')),
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT uk_hub_stall_location_code UNIQUE (location_id, code)
);

ALTER TABLE horse_stay ADD COLUMN hub_stall_id bigint REFERENCES hub_stall(id);

CREATE UNIQUE INDEX uk_horse_stay_open_hub_stall ON horse_stay (hub_stall_id)
    WHERE hub_stall_id IS NOT NULL AND actual_start_at IS NOT NULL AND actual_end_at IS NULL;
