ALTER TABLE vehicle ADD COLUMN service_role varchar(30) NOT NULL DEFAULT 'BRANCH'
    CHECK (service_role IN ('LINEHAUL', 'SPARE', 'BRANCH'));

ALTER TABLE departure_schedule
    ADD COLUMN base_vehicle_class_id bigint REFERENCES vehicle_class(id),
    ADD COLUMN base_vehicle_count int CHECK (base_vehicle_count > 0);

UPDATE departure_schedule s
SET base_vehicle_class_id = vc.id,
    base_vehicle_count = ceil(s.stall_capacity::numeric / vc.max_stall_count)::int
FROM vehicle_class vc WHERE vc.code = 'HEAVY';

ALTER TABLE departure_schedule
    ALTER COLUMN base_vehicle_class_id SET NOT NULL,
    ALTER COLUMN base_vehicle_count SET NOT NULL,
    DROP COLUMN stall_capacity;

CREATE TABLE departure_vehicle (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id bigint NOT NULL REFERENCES departure(id) ON DELETE CASCADE,
    vehicle_class_id bigint NOT NULL REFERENCES vehicle_class(id),
    vehicle_count int NOT NULL CHECK (vehicle_count > 0),
    allotment_type varchar(30) NOT NULL CHECK (allotment_type IN ('BASE', 'SPARE')),
    reason varchar(500),
    created_by bigint REFERENCES app_user(id),
    created_at timestamptz NOT NULL
);
CREATE INDEX ix_departure_vehicle_departure_id ON departure_vehicle (departure_id);

INSERT INTO departure_vehicle (departure_id, vehicle_class_id, vehicle_count, allotment_type, created_at)
SELECT d.id, vc.id, ceil(d.stall_capacity::numeric / vc.max_stall_count)::int, 'BASE', CURRENT_TIMESTAMP
FROM departure d CROSS JOIN vehicle_class vc WHERE vc.code = 'HEAVY';

UPDATE departure d SET stall_capacity = dv.vehicle_count * vc.max_stall_count
FROM departure_vehicle dv JOIN vehicle_class vc ON vc.id = dv.vehicle_class_id
WHERE dv.departure_id = d.id;

